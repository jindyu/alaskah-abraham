/** 기본 화자 / 배역 조회 (fallback 포함) */
export function getCast(id: string): CastMember {
  const norm = id.toLowerCase().replace(/\s+/g, '_');
  if (CAST_REGISTRY[norm]) return CAST_REGISTRY[norm];

  // 이름 기반 매핑 (예: "아브람" -> abram, "사라" -> sarah)
  for (const c of Object.values(CAST_REGISTRY)) {
    if (c.name === id || c.enName.toLowerCase() === norm) return c;
  }

  // 폴백 기본 인물
  return {
    id: norm,
    name: id,
    enName: id,
    role: '등장인물',
    scale: 1.0,
    skinColor: PAL.skin[2],
    tunicColor: PAL.fabric.ochre,
    hairColor: 0x3b281a,
    accentColor: PAL.fabric.cream,
    headpiece: 'none',
  };
}
